#!/usr/bin/env bash
# ==============================================================================
# web-tunnel.sh — быстрый безопасный доступ к веб-панели Timeline Notifier
#
# Не требует установки лишних программ, использует стандартный ssh.
# Работает через бесплатный сервис туннелей (pinggy.io / localhost.run).
# ==============================================================================

PORT="${1:-5000}"

echo "=========================================================="
echo "  🚀 Запуск временного HTTPS-туннеля к веб-панели (порт $PORT)..."
echo "  Нажми Ctrl+C, когда закончишь работу в веб-панели."
echo "=========================================================="
echo ""

# Проверяем доступность локального порта
if ! curl -s -o /dev/null -w "%{http_code}" "http://127.0.0.1:${PORT}/ping" | grep -q "200"; then
    echo "⚠️  Внимание: контейнер бота не отвечает на http://127.0.0.1:${PORT}/ping"
    echo "Убедись, что контейнеры запущены: docker compose ps"
    echo ""
fi

echo "Подключаюсь к pinggy.io..."
echo "Скопируй появившуюся ссылку https://... в браузер:"
echo "----------------------------------------------------------"

# Подключаемся через pinggy
ssh -p 443 -R0:localhost:${PORT} a.pinggy.io 2>/dev/null || {
    echo ""
    echo "pinggy недоступен, пробую резервный localhost.run..."
    ssh -R 80:localhost:${PORT} nokey@localhost.run
}
