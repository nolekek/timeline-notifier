def _get_rng(sign: str, day: date | None = None) -> random.Random:
    """Детерминированный генератор псевдослучайных чисел для знака и даты."""
    day = day or date.today()
    seed_str = f"{day.isoformat()}:{sign.lower().strip()}"
    seed_int = int(hashlib.md5(seed_str.encode('utf-8')).hexdigest(), 16)
    return random.Random(seed_int)


def normalize_zodiac_sign(sign: str | None) -> str | None:
    """Приводит русское или латинское название знака к ключу словаря ZODIAC_SIGNS."""
    if not sign:
        return None
    s = sign.strip().lower()
    for key, data in ZODIAC_SIGNS.items():
        if s == key:
            return key
        if s in (data['name'].lower(), data['symbol'], data['femboy_name'].lower()):
            return key
    # Нечеткий поиск
    aliases = {
        'овен': 'aries', 'овник': 'aries',
        'телец': 'taurus', 'тельчик': 'taurus',
        'близнецы': 'gemini', 'близняшки': 'gemini',
        'рак': 'cancer', 'рачок': 'cancer',
        'лев': 'leo', 'левушка': 'leo', 'лёва': 'leo',
        'дева': 'virgo', 'девственник': 'virgo',
        'весы': 'libra', 'весики': 'libra',
        'скорпион': 'scorpio', 'скорпик': 'scorpio',
        'стрелец': 'sagittarius', 'стрельчик': 'sagittarius',
        'козерог': 'capricorn', 'козерожек': 'capricorn',
        'водолей': 'aquarius', 'водолейчик': 'aquarius',
        'рыбы': 'pisces', 'рыбки': 'pisces', 'рыба': 'pisces',
    }
    return aliases.get(s)


def generate_horoscope(sign: str, day: date | None = None, user: Any = None) -> dict:
    """Генерирует структурированный студенческий гороскоп на указанный день."""
    norm_sign = normalize_zodiac_sign(sign) or 'aries'
    meta = ZODIAC_SIGNS[norm_sign]
    day = day or date.today()
    rng = _get_rng(norm_sign, day)

    is_femboy = bool(user and getattr(user, 'theme_femboy', False))

    if is_femboy:
        pred_pool = PREDICTIONS_FEMBOY + PREDICTIONS_STANDARD[:5]
        item_pool = LUCKY_ITEMS_FEMBOY + LUCKY_ITEMS_STANDARD[:4]
        adv_pool = ADVICES_FEMBOY + ADVICES_STANDARD[:3]
        display_name = meta['femboy_name']
    else:
        pred_pool = PREDICTIONS_STANDARD
        item_pool = LUCKY_ITEMS_STANDARD
        adv_pool = ADVICES_STANDARD
        display_name = f"{meta['symbol']} {meta['name']}"

    prediction = rng.choice(pred_pool)
    lucky_item = rng.choice(item_pool)
    advice = rng.choice(adv_pool)
    avtomat_chance = rng.randint(45, 99)

    return {
        'sign_key': norm_sign,
        'name': display_name,
        'symbol': meta['symbol'],
        'dates': meta['dates'],
        'date_str': day.strftime('%d.%m.%Y'),
        'prediction': prediction,
        'lucky_item': lucky_item,
        'advice': advice,
        'avtomat_chance': avtomat_chance,
        'is_femboy': is_femboy,
    }


def format_horoscope_html(horo: dict) -> str:
    """Форматирует гороскоп в виде красивой карточки с цитатой <blockquote>."""
    is_femboy = horo.get('is_femboy', False)
    header = (
        f"🐾 <b>Мурчащий гороскоп на {horo['date_str']} :3</b>\n"
        if is_femboy else
        f"🔮 <b>Студенческий гороскоп на {horo['date_str']}</b>\n"
    )

    lines = [
        header,
        f"<b>{html.escape(horo['name'])}</b> <i>({html.escape(horo['dates'])})</i>",
        "",
        f"<blockquote>{html.escape(horo['prediction'])}</blockquote>",
        "",
        f"{'🎀' if is_femboy else '🍀'} <b>Счастливый предмет:</b> {html.escape(horo['lucky_item'])}",
        f"{'💡' if not is_femboy else '🐾'} <b>Совет дня:</b> {html.escape(horo['advice'])}",
        f"🎯 <b>Шанс автомата:</b> <code>{horo['avtomat_chance']}%</code>",
    ]
    return "\n".join(lines)


def get_daily_horoscope_short(sign: str, day: date | None = None, user: Any = None) -> str:
    """Короткая версия гороскопа для утреннего дайджеста дедлайнов."""
    norm_sign = normalize_zodiac_sign(sign)
    if not norm_sign:
        return ""
    h = generate_horoscope(norm_sign, day=day, user=user)
    is_femboy = h.get('is_femboy', False)
    return (
        f"<b>{html.escape(h['name'])}:</b> <blockquote>{html.escape(h['prediction'])}</blockquote>\n"
        f"{'🎀' if is_femboy else '🍀'} <i>Совет: {html.escape(h['advice'])}</i>"
    )
