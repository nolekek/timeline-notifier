def joke(kind: str, seed: int | None = None) -> str:
    """Случайная шутка секции (или детерминированная, если задан seed)."""
    pool = JOKES.get(kind)
    if not pool:
        return ''
    if seed is None:
        return random.choice(pool)
    return pool[seed % len(pool)]


def joke_html(kind: str, seed: int | None = None) -> str:
    """Шутка в курсиве — как её и вставляем в сообщения."""
    text = joke(kind, seed)
    return f"<i>{text}</i>" if text else ''
